-- One-time migration: tour_medias was a plain join table (tour_id, media_id).
-- TourMedia now needs an id and a sort_order. Run this once BEFORE starting
-- the API, so existing tour images keep their upload order.

ALTER TABLE tour_medias ADD COLUMN IF NOT EXISTS id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY;
ALTER TABLE tour_medias ADD COLUMN IF NOT EXISTS sort_order INTEGER;

UPDATE tour_medias tm
SET sort_order = x.rn
FROM (
    SELECT id, ROW_NUMBER() OVER (PARTITION BY tour_id ORDER BY media_id) AS rn
    FROM tour_medias
) x
WHERE tm.id = x.id
  AND tm.sort_order IS NULL;

ALTER TABLE tour_medias ALTER COLUMN sort_order SET NOT NULL;
